import { LOCALE_CODES } from '@core/i18n/locales';

/**
 * Paths crawlers are kept out of, written without a language.
 *
 * Each is either authenticated, per-user, or carries a credential in the URL. Indexing
 * them wastes crawl budget on pages that render as a login wall to a crawler, and in the
 * tokened cases would publish the token itself.
 *
 * Search is deliberately NOT here. Every search URL carries its own directive — an
 * unfiltered one canonicalises to its `/hostels/:place` landing page, a filtered one is
 * `noindex` — and a crawler has to fetch the page to read either. Blocking it would hide
 * the very instructions that keep filter permutations out of the index.
 */
export const DISALLOWED_PATHS = [
  // Authenticated consoles — render client-side only, so a crawler sees an empty shell.
  'host',
  'admin',
  'moderator',
  'forbidden',
  // Per-user areas — nothing here is the same for two visitors.
  'account',
  'notifications',
  // Auth screens. Thin, duplicated, and /auth carries returnUrl variants that would
  // otherwise generate an unbounded set of near-identical URLs.
  'auth',
  // The token in the query string *is* the credential for these links.
  'confirm_invitation',
  'reset_password',
] as const;

/**
 * Paths that are a prefix of a public, indexable path, and so must be anchored.
 *
 * robots.txt matches on prefix: a bare `Disallow: /en/host` also blocks `/en/hostel/:id`
 * and `/en/hostels/:place` — every listing page and every SEO landing page this site has.
 * `$` anchors the console root, and the slash and `?` forms cover what follows it.
 */
const ANCHORED = new Set<string>(['host']);

/**
 * The `Disallow` patterns, one set per language plus the bare form.
 *
 * Every language is named rather than covered by one leading wildcard. In robots.txt `*`
 * matches any run of characters, slashes included — not one segment, as it does in the
 * server route table — so a wildcard-prefixed `auth` rule would also block
 * `/en/blog/authentic-…` and any later segment that happens to start with a blocked word.
 * Naming the codes matches only the real URL shape.
 *
 * Every routable language is listed, not only the indexed ones: an untranslated locale
 * still serves the page at its own prefix. The bare forms stay because an unprefixed URL
 * is real until the redirect to its prefixed twin lands, and crawlers already know them.
 */
export function disallowPatterns(): string[] {
  const prefixes = ['', ...LOCALE_CODES.map((code) => `/${code}`)];
  return prefixes.flatMap((prefix) =>
    DISALLOWED_PATHS.flatMap((path) =>
      ANCHORED.has(path)
        ? [`${prefix}/${path}$`, `${prefix}/${path}/`, `${prefix}/${path}?`]
        : [`${prefix}/${path}`],
    ),
  );
}

/**
 * Renders `/robots.txt`.
 *
 * Generated from `LOCALE_CODES` for the same reason the sitemap is: a language added to
 * the app is covered here with no second edit, so the file cannot fall behind the routes
 * the way the old static one did when every URL gained its prefix.
 */
export function renderRobotsTxt(origin: string): string {
  return [
    `# HostelHive — ${origin}`,
    '# Generated by the SSR server (apps/web/src/app/core/robots.ts).',
    '',
    'User-agent: *',
    ...disallowPatterns().map((pattern) => `Disallow: ${pattern}`),
    'Allow: /',
    '',
    `Sitemap: ${origin}/sitemap.xml`,
    '',
  ].join('\n');
}
